/**
 * Supabase migration workflow (migration map, stage 1). packages/db/migrations stays the source of truth for the
 * running Fastify stack (hand-written SQL applied by packages/db/src/migrate.ts, tracked in
 * platform.schema_migrations). This copies each file unchanged into supabase/migrations under the CLI's timestamped
 * name (NNNN → 20261001 + six-digit NNNN), so `supabase db reset` builds the same schema from scratch.
 *
 *   node --import tsx scripts/supabase/sync-migrations.ts           write missing or changed copies
 *   node --import tsx scripts/supabase/sync-migrations.ts --check   exit 1 if the two folders differ (CI)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const source = join(repo, "packages", "db", "migrations");
const target = join(repo, "supabase", "migrations");

export function supabaseName(file: string): string {
  const m = /^(\d{4})_([a-z0-9_]+\.sql)$/.exec(file);
  if (!m) throw new Error(`unexpected migration file name ${file}`);
  return `20261001${(m[1] ?? "").padStart(6, "0")}_${m[2] ?? ""}`;
}

/**
 * What packages/db/src/migrate.ts does before the first file: the platform schema and its migration ledger. Under the
 * Supabase CLI this has to be a migration of its own, applied first.
 */
export const PRELUDE_NAME = "20261001000000_migration_runner_prelude.sql";
export const PRELUDE = `-- Generated by scripts/supabase/sync-migrations.ts: what packages/db/src/migrate.ts creates before the first migration.
create schema if not exists platform;
create table if not exists platform.schema_migrations (
  name text primary key, checksum text not null, applied_at timestamptz not null default now());
`;

export function plan(): { file: string; name: string; body: string; current: string | null }[] {
  const prelude = existsSync(join(target, PRELUDE_NAME)) ? readFileSync(join(target, PRELUDE_NAME), "utf8") : null;
  return [{ file: "(runner prelude)", name: PRELUDE_NAME, body: PRELUDE, current: prelude }, ...readdirSync(source)
    .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f))
    .sort()
    .map((file) => {
      const name = supabaseName(file);
      const path = join(target, name);
      return { file, name, body: readFileSync(join(source, file), "utf8"), current: existsSync(path) ? readFileSync(path, "utf8") : null };
    })];
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const items = plan();
  const extra = existsSync(target) ? readdirSync(target).filter((f) => f.endsWith(".sql") && !items.some((i) => i.name === f)) : [];
  const stale = items.filter((i) => i.current !== i.body);
  if (check) {
    for (const i of stale) console.error(`${i.current === null ? "missing" : "differs"}: supabase/migrations/${i.name} (from ${i.file})`);
    for (const f of extra) console.error(`not in packages/db/migrations: supabase/migrations/${f}`);
    if (stale.length || extra.length) process.exit(1);
    console.log(`supabase/migrations matches packages/db/migrations (${items.length} files)`);
  } else {
    if (extra.length) throw new Error(`supabase/migrations has files with no source: ${extra.join(", ")}`);
    mkdirSync(target, { recursive: true });
    for (const i of stale) writeFileSync(join(target, i.name), i.body);
    console.log(`wrote ${stale.length} of ${items.length} migrations to supabase/migrations`);
  }
}
